def main():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "確認事項"
    f = lambda **kw: Font(name="游ゴシック", size=kw.pop("size", 10), **kw)
    thin = Side(style="thin", color="A6A6A6")
    box = Border(left=thin, right=thin, top=thin, bottom=thin)
    ws["A1"] = "上田さん・各担当者への確認事項 v01（八幡地区 常駐体制検証）"
    ws["A1"].font = f(size=14, bold=True)
    ws["A2"] = "誰が：上田さん（一部は西日本海運担当者）　何を見て：各行の「対象資料」　どこへ：薄黄色の「回答」「回答日」「回答者」欄へ入力。分からない場合は「不明」と入力してください。"
    ws["A3"] = "回答をもとに、元帳の時刻の扱い・マスター・前日確定などを更新します。推測では埋めません。"
    for c in ("A2", "A3"):
        ws[c].font = f()
    heads = [("No【自動】", 6, "auto"), ("区分【自動】", 14, "auto"), ("確認相手【自動】", 16, "auto"),
             ("確認する内容【自動】", 60, "auto"), ("必要な理由【自動】", 44, "auto"), ("対象資料【自動】", 34, "auto"),
             ("現在分かっていること【自動】", 36, "auto"), ("回答【入力】", 40, "in"), ("回答日【入力】", 12, "in"),
             ("回答者【入力】", 10, "in"), ("状況【入力・選択】", 10, "in")]
    for i, (t, w, k) in enumerate(heads, 1):
        c = ws.cell(5, i, t)
        c.font = f(bold=True)
        c.fill = PatternFill("solid", fgColor="FFE97F" if k == "in" else "BFBFBF")
        c.alignment = Alignment(wrap_text=True, horizontal="center", vertical="center")
        c.border = box
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    for n, item in enumerate(ITEMS, 1):
        r = 5 + n
        vals = (n,) + item + (None, None, None, "未回答")
        for i, v in enumerate(vals, 1):
            c = ws.cell(r, i, v)
            c.font = f()
            c.alignment = Alignment(wrap_text=True, vertical="top")
            c.border = box
            c.fill = PatternFill("solid", fgColor="FFF9C4" if i >= 8 else "EDEDED")
        ws.cell(r, 9).number_format = "yyyy/mm/dd"
    dv = DataValidation(type="list", formula1='"未回答,回答済み,不明,資料なし"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"K6:K{5 + len(ITEMS)}")
    ws.freeze_panes = "D6"
    ws.sheet_view.selection[0].activeCell = "H6"
    ws.sheet_view.selection[0].sqref = "H6"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    wb.save(OUT)
    print("saved", OUT, len(ITEMS))


if __name__ == "__main__":
    main()
